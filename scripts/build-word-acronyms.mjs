// Regenerates the list of acronyms said as words in extension/lib/textkit.js
// (000068).
//
//   node scripts/build-word-acronyms.mjs      (needs `uv sync --directory server`)
//
// The browser engine voices words through espeak-ng, which spells a short
// all-caps word in lowercase text unless it knows it: "16 gigabytes of RAM"
// was "R-A-M". The server's misaki has a dictionary and says "ram". So the
// list comes from misaki: every all-caps word its dictionary says exactly
// like the lowercase word, kept only where espeak reads the lowercase form
// differently from the capitals (lowercasing would change nothing
// otherwise). textkit sends those words lowercase.
//
// The output is written between the generated markers in textkit.js and
// committed, so neither the extension nor the tests need the server installed.
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { phonemize } from "phonemizer";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TEXTKIT = path.join(ROOT, "extension", "lib", "textkit.js");
const BEGIN = "  // BEGIN GENERATED by scripts/build-word-acronyms.mjs";
const END = "  // END GENERATED";

const MISAKI = `
import json, importlib.resources as r
d = json.loads((r.files("misaki") / "data" / "us_gold.json").read_text())
print(json.dumps(sorted(
    k for k, v in d.items()
    if k.isupper() and k.isalpha() and 2 <= len(k) <= 6
    and isinstance(v, str) and d.get(k.lower()) == v
)))
`;

const candidates = JSON.parse(
  execFileSync(path.join(ROOT, "server", ".venv", "bin", "python"), ["-I", "-c", MISAKI], { encoding: "utf8" })
);

// In a sentence, because espeak only spells capitals among lowercase words.
const inSentence = async (word) => (await phonemize(`the ${word} is here`, "en-us")).join(" ");
const words = [];
for (const word of candidates) {
  if ((await inSentence(word)) !== (await inSentence(word.toLowerCase()))) words.push(word);
}

const lines = [];
let line = "   ";
for (const word of words) {
  if (line.length + word.length + 1 > 78) {
    lines.push(line);
    line = "   ";
  }
  line += ` ${word}`;
}
lines.push(line);

const block = [BEGIN, "  const WORD_ACRONYMS = new Set(`", ...lines, "  `.trim().split(/\\s+/));", END].join("\n");
const source = await readFile(TEXTKIT, "utf8");
const start = source.indexOf(BEGIN);
const end = source.indexOf(END);
if (start === -1 || end === -1) throw new Error("generated markers not found in textkit.js");
await writeFile(TEXTKIT, source.slice(0, start) + block + source.slice(end + END.length));
console.log(`${words.length} of ${candidates.length} acronyms written to extension/lib/textkit.js`);
